// Inlines webview/ into src/webview-html.ts. Drawdy builds only src/ with no
// bundler plugins, so the generated module is committed as source.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (p) => readFileSync(root + p, "utf8");

const { outputFiles } = await build({
    entryPoints: [root + "webview/app.ts"],
    bundle: true,
    format: "iife",
    target: "es2020",
    write: false,
    charset: "utf8",
});
const script = outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = read("webview/index.html")
    .replace("/*__STYLES__*/", () => read("webview/styles.css"))
    .replace("/*__SCRIPT__*/", () => script);

writeFileSync(
    root + "src/webview-html.ts",
    `// Generated by scripts/build-webview.mjs from webview/. Do not edit.\nexport const WEBVIEW_HTML = ${JSON.stringify(html)};\n`
);
console.log(`src/webview-html.ts: ${(html.length / 1024).toFixed(1)} KB`);
